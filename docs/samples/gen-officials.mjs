// ── Generate ────────────────────────────────────────────────────────────────
const lordOf = new Map() // successionの君主名 → その朝代（肩書）
for (const [t, list] of dyns) for (const e of list) lordOf.set(e.name, t)

let err = 0
const summary = []
const order = [...dyns.entries()]
  .map(([dyn, list]) => ({ dyn, list, span: spanOf(list) }))
  .sort((a, b) => startYearOf(a.span) - startYearOf(b.span))

for (const [i, { dyn, list, span }] of order.entries()) {
  const offs = OFFICIALS[dyn]
  if (!offs) { console.log(`!! OFFICIALSデータが無い肩書「${dyn}」`); err++; continue }
  const names = new Set(offs.map((o) => o[0]))
  if (names.size !== offs.length) { console.log(`!! 官僚名の重複: ${dyn}`); err++ }

  // 主君参照の検証と注入候補の収集
  const injected = new Set()
  for (const o of offs) {
    const liege = o[5]
    if (!liege) continue
    if (names.has(liege) || EXTRA[liege] || lordOf.has(liege)) { if (lordOf.has(liege)) injected.add(liege); continue }
    console.log(`!! 未解決の主君: ${dyn}/${o[0]} → ${liege}`); err++
  }

  // 行の構成: 官僚 → 参照された君主（継承録由来 → 注入、EXTRA由来 → 付加）
  const rows = offs.map((o) => [o[0], o[1] || '男', o[2] || '', o[3] || '', o[4], o[5] || '', o[6] || '', o[7] || ''])
  for (const ln of injected) {
    const g = lordOf.get(ln)
    const e = dyns.get(g).find((x) => x.name === ln)
    const t = TITLE_OVERRIDE[ln] || (TITLE[g] === 'EMBED' ? embedTitle(ln) : (TITLE[g] || '皇帝'))
    rows.push([ln, ln === '武周則天武曌' ? '女' : '男', e.b, e.d, t, '', e.p, `${g}の君主`])
  }
  for (const k of new Set(offs.map((o) => o[5]).filter((l) => l && EXTRA[l]))) {
    const x = EXTRA[k]
    rows.push([k, x.g || '男', x.b || '', x.d || '', x.t || '', '', '', x.n || ''])
  }

  const fname = `china-${String(i + 1).padStart(2, '0')}-${dyn.replace(/·/g, '-')}-${span}-officials.csv`
  const csv = ['名前,性別,生年,没年,肩書,主君,期間,メモ', ...rows.map((r) => r.join(','))].join('\n')
  fs.writeFileSync(`${OUT}/${fname}`, csv)
  summary.push(`  ${dyn} (${span}): 官僚${offs.length} + 君主${injected.size} = ${rows.length}行 → ${fname}`)
}

console.log(summary.join('\n'))
console.log(err ? `\n${err} 個のエラー` : '\nOK: 55ファイル生成完了（主君参照すべて解決）')
