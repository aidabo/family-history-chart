// Generate per-dynasty officials CSVs (君臣・将・軍師・謀士・政治/経済/軍事/外交の人物)
// from china-imperial-succession.csv: china-NN-{朝代}-{期間}-officials.csv
// into docs/samples/01-China/. NN = same chronological order as the family series.
// Format: 名前,性別,生年,没年,肩書,主君,期間,メモ
//   主君 = lord（君臣関係）。主君は china-imperial-succession.csv の君主（他朝代でも可）
//   または EXTRA（春秋の諸侯・曹操など君主録に無い主君）。参照された君主は行として自動収録。
// Validation: 肩書ごとにデータが揃っていること、主君参照が全て解決すること。
//
// Usage: node docs/samples/gen-officials.mjs

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const DIR = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.join(DIR, '01-China')

const src = fs.readFileSync(`${OUT}/china-imperial-succession.csv`, 'utf8').replace(/^﻿/, '')
const lines = src.trim().split(/\r?\n/)
const header = lines[0].split(',')
const H = Object.fromEntries(header.map((h, i) => [h, i]))
const dyns = new Map() // 肩書 → [{name,b,d,p}]
for (const l of lines.slice(1)) {
  if (!l.trim()) continue
  const c = l.split(',')
  const name = c[H['名前']], t = c[H['肩書']]
  if (!name) continue
  if (!dyns.has(t)) dyns.set(t, [])
  dyns.get(t).push({ name, b: c[H['生年']] || '', d: c[H['没年']] || '', p: c[H['期間']] || '' })
}

