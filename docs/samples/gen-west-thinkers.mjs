// 著作は「；」「空白」「《の直前」で分割（《国家》《饗宴》 → 《国家》；《饗宴》 で別ノードに）
const splitWorks = (v) => (v || '').split(/[；;]+|\s+|(?=《)/).map((s) => s.trim()).filter(Boolean)

// 検証
const names = new Set(THINKERS.map((p) => p[0]))
if (names.size !== THINKERS.length) {
  const dup = THINKERS.map((p) => p[0]).filter((n, i, a) => a.indexOf(n) !== i)
  throw new Error(`名前の重複: ${[...new Set(dup)].join(', ')}`)
}
const badTeacher = []
for (const p of THINKERS) {
  for (const t of (p[6] || '').split(/[；;]/).map((s) => s.trim()).filter(Boolean)) {
    if (!names.has(t)) badTeacher.push(`${p[0]}→${t}`)
  }
}
if (badTeacher.length) throw new Error(`未解決の師参照: ${badTeacher.join(', ')}`)
const workCollision = []
for (const p of THINKERS) {
  for (const w of splitWorks(p[8])) {
    if (names.has(w)) workCollision.push(`${p[0]}→${w}`)
  }
}
if (workCollision.length) throw new Error(`人物名と衝突する著作: ${workCollision.join(', ')}`)

// 生年順ソート
const yearOf = (v) => Number((v || '').replace(/[约約]/g, '').replace(/^前/, '-'))
const sortKey = (p) => {
  const b = yearOf(p[2])
  return p[2] !== '' && Number.isFinite(b) ? b : yearOf(p[3])
}
const rows = [...THINKERS].sort((a, b) => sortKey(a) - sortKey(b))

// 翻訳ヘルパ（欠落は日本語のまま）
const missing = { en: 0, zh: 0 }
const tr = (map, ja, lang, kind) => {
  if (lang === 'ja' || !ja) return ja || ''
  const v = map[ja]?.[lang]
  if (!v) missing[lang]++
  return v ?? ja
}
const gender = (g, lang) => (lang === 'en' ? (g === '女' ? 'female' : 'male') : g)
const refs = (v, lang) => (v || '').split(/[；;]/).map((s) => s.trim()).filter(Boolean).map((s) => tr(NAMES, s, lang)).join('；')
const worksTr = (v, lang) => splitWorks(v).map((s) => tr(WORKS, s, lang)).join('；')

for (const { dir, lang } of VARIANTS) {
  const OUT = path.join(DIR, dir)
  fs.mkdirSync(OUT, { recursive: true })
  const header = lang === 'en'
    ? 'name,gender,birth,death,era,title,teacher,school,works,period,note'
    : '名前,性別,生年,没年,時代,肩書,師,学派,著作,期間,メモ'
  const cell = (v) => {
    const s = String(v ?? '')
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
  }
  const csv = [header, ...rows.map((r) =>
    [tr(NAMES, r[0], lang), gender(r[1], lang), r[2], r[3], tr(ERAS, r[4], lang),
     tr(TITLES, r[5], lang), refs(r[6], lang), r[7], worksTr(r[8], lang), r[9], tr(MEMOS, r[10], lang)].map(cell).join(','))].join('\n')
  fs.writeFileSync(path.join(OUT, 'west-thinkers.csv'), csv)
  console.log(`${dir}: west-thinkers.csv（${rows.length}人）`)
}

const works = new Set(rows.flatMap((p) => splitWorks(p[8])))
const teachers = new Set(rows.flatMap((p) => (p[6] || '').split(/[；;]/).map((s) => s.trim()).filter(Boolean)))
console.log(`  師エッジ ${teachers.size}人・著作ノード ${works.size}件`)
console.log(`英語未翻訳 ${missing.en}・中国語未翻訳 ${missing.zh}`)

