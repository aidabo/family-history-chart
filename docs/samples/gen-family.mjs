// Generate per-dynasty family-relationship CSVs from china-imperial-succession.csv
// Output format (referencing china-three-kingdoms.csv):
//   名前,性別,生年,没年,父,母,配偶者,養父,養母,肩書,期間,メモ
// 1 row = 1 person. Emperors come from the succession file; FAMILY adds the
// family relations (父/母/配偶者/養父/養母) and EXTRA rows (wives, fathers, etc.).
// Validation: every rel key must be an emperor of that dynasty; every referenced
// name must resolve to an emperor or an extra of the same file.
//
// Usage: node docs/samples/gen-family.mjs   (writes china-NN-{朝代}-{期間}-family.csv into
//                                           docs/samples/01-China/; NN = chronological order by span start year)

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const DIR = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.join(DIR, '01-China') // ソースCSVと出力CSVはこのフォルダに置く

const src = fs.readFileSync(`${OUT}/china-imperial-succession.csv`, 'utf8').replace(/^﻿/, '')
const lines = src.trim().split(/\r?\n/)
const header = lines[0].split(',')
const H = Object.fromEntries(header.map((h, i) => [h, i]))
const dyns = new Map() // 肩書 → [{name,b,d,p}]
for (const l of lines.slice(1)) {
  if (!l.trim()) continue
  const c = l.split(',')
  const name = c[H['名前']], t = c[H['肩書']]
  if (!name) continue
  if (!dyns.has(t)) dyns.set(t, [])
  dyns.get(t).push({ name, b: c[H['生年']] || '', d: c[H['没年']] || '', p: c[H['期間']] || '' })
}

