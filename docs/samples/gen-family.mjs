// ── 肩書 resolution ─────────────────────────────────────────────────────────
const TITLE = {
  '夏': '帝', '商': '帝',
  '西周': '王', '東周·春秋': '王', '東周·戰國': '王',
  '戰國·齊': 'EMBED', '戰國·楚': 'EMBED', '戰國·燕': 'EMBED',
  '戰國·韓': 'EMBED', '戰國·趙': 'EMBED', '戰國·魏': 'EMBED', '戰國·秦': 'EMBED',
  '吳': '王', '吳越': '王', '楚': '王', '閩': '王', '荊南': '王',
}
const TITLE_OVERRIDE = { '共和': '攝政', '孺子嬰劉嬰': '皇太子' }
const embedTitle = (n) => {
  const ms = [...n.matchAll(/太公|出子|王|侯|公/g)]
  return ms.length ? ms[ms.length - 1][0] : ''
}

const spanOf = (list) => {
  const s = list[0].p.split(';')[0].split('-')[0]
  const ps = list[list.length - 1].p.split(';')
  return `${s}-${ps[ps.length - 1].split('-').pop()}`
}
const startYearOf = (span) => { // 前N → -N (BC), N → N
  const m = span.match(/^前(\d+)/)
  return m ? -Number(m[1]) : Number(span.split('-')[0])
}

// ── Generate ────────────────────────────────────────────────────────────────
// File names get a zero-padded prefix in chronological order (by span start year)
let err = 0
const summary = []
const order = [...dyns.entries()]
  .map(([dyn, list]) => ({ dyn, list, span: spanOf(list) }))
  .sort((a, b) => startYearOf(a.span) - startYearOf(b.span)) // stable: ties keep succession-CSV order
for (const [i, { dyn, list, span }] of order.entries()) {
  const fam = FAMILY[dyn]
  if (!fam) { console.log(`!! FAMILYデータが無い肩書「${dyn}」(${list.length}人)`); err++; continue }

  const em = new Set(list.map((e) => e.name))
  const ex = new Set(Object.keys(fam.extra))

  // 1) rel keys must be emperors of this dynasty
  for (const k of Object.keys(fam.rel)) {
    if (!em.has(k)) { console.log(`!! rel key が帝王に存在しない: ${dyn} / ${k}`); err++ }
    if (ex.has(k)) { console.log(`!! rel key が extra と重複: ${k}`); err++ }
  }
  // 2) every referenced name must resolve
  const all = new Set([...em, ...ex])
  const check = (ref, ctx) => { if (ref && !all.has(ref)) { console.log(`!! 未解決の参照: ${ctx} → ${ref}`); err++ } }
  for (const [k, r] of Object.entries(fam.rel)) {
    if (r.f) check(r.f, `${dyn}/${k}の父`)
    if (r.m) check(r.m, `${dyn}/${k}の母`)
    for (const s of r.sp || []) check(s, `${dyn}/${k}の配偶者`)
    if (r.ff) check(r.ff, `${dyn}/${k}の養父`)
    if (r.fm) check(r.fm, `${dyn}/${k}の養母`)
  }
  for (const [k, x] of Object.entries(fam.extra)) {
    if (em.has(k)) { console.log(`!! extra が帝王と重複: ${k}`); err++ }
    if (x.f) check(x.f, `${dyn}/extra ${k}の父`)
    if (x.sp) check(x.sp, `${dyn}/extra ${k}の配偶者`)
  }

  // 3) compose rows
  const rows = []
  for (const e of list) {
    const r = fam.rel[e.name] || {}
    const g = e.name === '武周則天武曌' ? '女' : '男'
    const t = TITLE_OVERRIDE[e.name] || (TITLE[dyn] === 'EMBED' ? embedTitle(e.name) : (TITLE[dyn] || '皇帝'))
    rows.push([e.name, g, e.b, e.d, r.f || '', r.m || '', (r.sp || []).join('；'), r.ff || '', r.fm || '', t, e.p, r.n || ''])
  }
  for (const [k, x] of Object.entries(fam.extra)) {
    let sp = x.sp || ''
    if (!sp) {
      for (const [kn, r] of Object.entries(fam.rel)) {
        if ((r.sp || []).includes(k)) { sp = kn; break }
      }
    }
    rows.push([k, x.g || '女', x.b || '', x.d || '', x.f || '', '', sp, '', '', x.t || '', '', x.n || ''])
  }

  const fname = `china-${String(i + 1).padStart(2, '0')}-${dyn.replace(/·/g, '-')}-${span}-family.csv`
  const csv = ['名前,性別,生年,没年,父,母,配偶者,養父,養母,肩書,期間,メモ',
    ...rows.map((r) => r.join(','))].join('\n')
  fs.writeFileSync(`${OUT}/${fname}`, csv)
  summary.push(`  ${dyn} (${span}): 帝王${list.length} + 追加${rows.length - list.length} = ${rows.length}行 → ${fname}`)
}

console.log(summary.join('\n'))
console.log(err ? `\n${err} 個のエラー` : '\nOK: 55ファイル生成完了（全参照解決済み）')
